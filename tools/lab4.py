def mk(n):
    return f'<span class="mk">{n}</span>'



def chain(*items):
    out = []
    for k, (name, pid, note, kind) in enumerate(items):
        if k:
            out.append(V.arrow('запустил'))
        out.append(V.card(f'номер {pid}', f'<code>{name}</code>', f'<small>{note}</small>' if note else '', kind))
    return V.steps(*out)


