def orphan(parent, child, after, kind):
    return V.steps(V.card('родитель', f'<code>{parent}</code>', '<small>запустил и закрылся</small>', 'bad'), V.arrow('номер родителя был'),
                   V.card('сирота', f'<code>{child}</code>', '', 'py'), V.arrow('номер родителя стал'),
                   V.card('новый родитель', after, '', kind))


